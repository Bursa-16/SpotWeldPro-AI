# Mapping of non-Latin-1 chars to ASCII approximations for PDF core-font output
_TR_PDF_MAP = str.maketrans({
    ord("ş"): "s", ord("Ş"): "S",
    ord("ğ"): "g", ord("Ğ"): "G",
    ord("ü"): "u", ord("Ü"): "U",
    ord("ı"): "i", ord("İ"): "I",
    ord("ö"): "o", ord("Ö"): "O",
    ord("ç"): "c", ord("Ç"): "C",
    ord("—"): "--",  # em dash
    ord("–"): "-",   # en dash
    ord("‘"): "'", ord("’"): "'",
    ord("“"): '"', ord("”"): '"',
})


def _pdf_str(s: str) -> str:
    """Transliterate non-Latin-1 characters for FPDF core-font rendering."""
    try:
        s.encode("latin-1")
        return s
    except UnicodeEncodeError:
        return s.translate(_TR_PDF_MAP).encode("latin-1", errors="replace").decode("latin-1")


_INJECTION_PATTERN = re.compile(r"^[=+\-@\t\r]")


def _safe_cell(v: Optional[str]) -> str:
    """Prefix any cell that starts with formula-injection characters."""
    if v is None:
        return ""
    sv = str(v)
    if _INJECTION_PATTERN.match(sv):
        return "'" + sv  # safe apostrophe prefix (stripped by Excel on input)
    return sv


def _fmt(v: Optional[float], digits: int = 4) -> str:
    if v is None:
        return "--"
    return f"{v:.{digits}f}"


def _fmt_int(v: Optional[int]) -> str:
    if v is None:
        return "--"
    return f"{v:,}"


# ── Report context ─────────────────────────────────────────────────────────────

@dataclass
class ReportContext:
    aggr: MultiSpotAggregation
    extras: DashboardExtras
    report_id: str
    generated_at: str
    project_id: Optional[str]
    project_name: Optional[str]
    part_id: Optional[str]
    passport_id: Optional[str]
    report_language: str
    analyst_name: Optional[str]
    report_title: Optional[str]
    input_hash: str
    app_version: str


def build_report_context(
    specs: list[WeldPointEnergySpec],
    *,
    production_volume_annual: Optional[int] = None,
    tariff_eur_per_kwh: Optional[float] = None,
    tariff_usd_per_kwh: Optional[float] = None,
    pareto_top_n: int = 50,
    project_id: Optional[str] = None,
    project_name: Optional[str] = None,
    part_id: Optional[str] = None,
    passport_id: Optional[str] = None,
    report_language: str = "en",
    analyst_name: Optional[str] = None,
    report_title: Optional[str] = None,
    input_hash: Optional[str] = None,
) -> ReportContext:
    aggr = aggregate_multi_spot(
        specs,
        production_volume_annual=production_volume_annual,
        tariff_eur_per_kwh=tariff_eur_per_kwh,
        tariff_usd_per_kwh=tariff_usd_per_kwh,
        pareto_top_n=pareto_top_n,
    )
    extras = compute_dashboard_extras(
        aggr.rows,
        part_excess_kj=aggr.part_e_excess_total_kj,
        production_volume_annual=production_volume_annual,
        tariff_eur_per_kwh=tariff_eur_per_kwh,
        tariff_usd_per_kwh=tariff_usd_per_kwh,
    )
    now = datetime.now(timezone.utc)
    ts = now.strftime("%Y%m%dT%H%M%SZ")
    if not input_hash:
        input_hash = "COMPUTED"
    report_id = f"SWP-RPT-{now.strftime('%Y%m%d-%H%M%S')}-{input_hash[:8].upper()}"
    return ReportContext(
        aggr=aggr,
        extras=extras,
        report_id=report_id,
        generated_at=ts,
        project_id=project_id,
        project_name=project_name,
        part_id=part_id,
        passport_id=passport_id,
        report_language=report_language,
        analyst_name=analyst_name,
        report_title=report_title or "Energy Analysis Report",
        input_hash=input_hash,
        app_version=_APP_VERSION,
    )


# ── CSV generator ─────────────────────────────────────────────────────────────

def generate_csv_report(ctx: ReportContext) -> bytes:
    """Return UTF-8 BOM CSV bytes (Excel-compatible)."""
    buf = io.StringIO()
    w = csv.writer(buf)

    def section(title: str) -> None:
        w.writerow([])
        w.writerow([f"### {title} ###"])

    def kv(k: str, v: str) -> None:
        w.writerow([_safe_cell(k), _safe_cell(v)])

    # ── Metadata ──────────────────────────────────────────────────────────
    section("REPORT METADATA")
    kv("Report ID", ctx.report_id)
    kv("Generated At (UTC)", ctx.generated_at)
    kv("Application Version", ctx.app_version)
    kv("Input Snapshot Hash", ctx.input_hash)
    kv("Report Language", ctx.report_language.upper())
    kv("Project ID", ctx.project_id or "—")
    kv("Project Name", ctx.project_name or "—")
    kv("Part ID", ctx.part_id or "—")
    kv("Digital Weld Passport ID", ctx.passport_id or "—")
    kv("Analyst", ctx.analyst_name or "—")
    kv("Report Title", ctx.report_title or "—")

    # ── KPI Summary ───────────────────────────────────────────────────────
    section("PART ENERGY KPI SUMMARY")
    a = ctx.aggr
    kv("Total Weld Points", str(a.part_point_count))
    kv("Points In-Window", str(a.part_points_in_window))
    kv("Points Below Min", str(a.part_points_below_min))
    kv("Points Above Max", str(a.part_points_above_max))
    kv("Points Not-Established", str(a.part_points_not_established))
    kv("Points Quality Risk (E_cur < E_ideal)", str(a.part_points_quality_risk))
    kv("Part E_current Total (kJ)", _fmt(a.part_e_current_total_kj))
    kv("Part E_ideal Total (kJ)", _fmt(a.part_e_ideal_total_kj))
    kv("Part E_excess Total (kJ) [THEORETICAL]", _fmt(a.part_e_excess_total_kj))
    if a.annual_e_excess_total_kwh is not None:
        kv("Annual Excess Energy (kWh) [THEORETICAL]", _fmt(a.annual_e_excess_total_kwh))
    if a.annual_cost_eur is not None:
        kv("Annual Cost Impact EUR [THEORETICAL]", _fmt(a.annual_cost_eur, 2))
    if a.annual_cost_usd is not None:
        kv("Annual Cost Impact USD [THEORETICAL]", _fmt(a.annual_cost_usd, 2))

    # ── Weld Points Table ─────────────────────────────────────────────────
    section("WELD POINTS DETAIL")
    w.writerow(["Point Code", "Group", "E_current(kJ)", "E_min(kJ)", "E_ideal(kJ)",
                "E_max(kJ)", "E_excess(kJ)", "Window Status", "Quality Risk",
                "Validation Status"])
    for row in ctx.aggr.rows:
        s = row.spec
        wn = row.window
        w.writerow([
            _safe_cell(s.point_code),
            _safe_cell(s.group_name),
            _fmt(wn.e_current_kj),
            _fmt(wn.e_min_kj),
            _fmt(wn.e_ideal_kj),
            _fmt(wn.e_max_kj),
            _fmt(wn.e_excess_potential_kj),
            wn.window_status.value,
            "YES" if wn.quality_risk_flag else "NO",
            s.validation_status.value,
        ])

    # ── Group Summary ─────────────────────────────────────────────────────
    section("GROUP SUMMARY")
    w.writerow(["Group Name", "Points", "In-Window", "Below Min", "Above Max",
                "Not Estab.", "Quality Risk", "E_current Total(kJ)", "E_ideal Total(kJ)",
                "E_excess Total(kJ)"])
    for g in ctx.aggr.groups:
        w.writerow([
            _safe_cell(g.group_name),
            g.point_count,
            g.points_in_window,
            g.points_below_min,
            g.points_above_max,
            g.points_not_established,
            g.points_quality_risk,
            _fmt(g.e_current_total_kj),
            _fmt(g.e_ideal_total_kj),
            _fmt(g.e_excess_total_kj),
        ])

    # ── Pareto Analysis ───────────────────────────────────────────────────
    section("PARETO ANALYSIS (by excess energy, descending)")
    w.writerow(["Rank", "Point Code", "Group", "E_current(kJ)", "E_ideal(kJ)",
                "E_excess(kJ)", "% of Total Excess", "Cumulative %", "Window Status"])
    for i, p in enumerate(ctx.extras.pareto_detailed, 1):
        w.writerow([
            i,
            _safe_cell(p.point_code),
            _safe_cell(p.group_name),
            _fmt(p.e_current_kj),
            _fmt(p.e_ideal_kj),
            _fmt(p.e_excess_kj),
            _fmt(p.pct_of_total_excess, 2),
            _fmt(p.cumulative_pct, 2),
            p.window_status,
        ])

    # ── Financial Summary ─────────────────────────────────────────────────
    f = ctx.extras.financial
    if f:
        section("FINANCIAL ANALYSIS [THEORETICAL — SEE DISCLAIMER]")
        kv("Avg Excess per Spot (kJ)", _fmt(f.avg_excess_per_spot_kj))
        kv("Avg Excess per Spot (kWh)", _fmt(f.avg_excess_per_spot_kwh, 8))
        kv("Part Excess Total (kJ)", _fmt(f.part_excess_kj))
        kv("Part Excess Total (kWh)", _fmt(f.part_excess_kwh, 8))
        kv("Per 1000 Parts Excess (kWh)", _fmt(f.per_1000_parts_excess_kwh))
        kv("Per 1000 Parts Cost EUR", _fmt(f.cost_eur_per_1000_parts, 2))
        kv("Per 1000 Parts Cost USD", _fmt(f.cost_usd_per_1000_parts, 2))
        kv("Annual Excess (kWh)", _fmt(f.annual_excess_kwh))
        kv("Annual Cost EUR", _fmt(f.annual_cost_eur, 2))
        kv("Annual Cost USD", _fmt(f.annual_cost_usd, 2))
        kv("Annual Production Volume (parts/year)", _fmt_int(f.production_volume_annual))
        kv("EUR Tariff (EUR/kWh)", _fmt(f.tariff_eur_per_kwh, 4))
        kv("USD Tariff (USD/kWh)", _fmt(f.tariff_usd_per_kwh, 4))

    # ── Sensitivity Matrix ────────────────────────────────────────────────
    if ctx.extras.sensitivity:
        section("SENSITIVITY MATRIX — Annual Cost EUR by Volume x EUR Tariff [THEORETICAL]")
        # Group by volume
        vol_map: dict[int, list[SensitivityRow]] = {}
        for sr in ctx.extras.sensitivity:
            vol_map.setdefault(sr.production_volume, []).append(sr)
        tariffs = sorted({sr.tariff_eur_per_kwh for sr in ctx.extras.sensitivity})
        header = ["Production Volume (parts/yr)"] + [f"EUR/kWh={t}" for t in tariffs]
        w.writerow(header)
        for vol in sorted(vol_map):
            row_map = {sr.tariff_eur_per_kwh: sr.cost_eur for sr in vol_map[vol]}
            w.writerow([_fmt_int(vol)] + [_fmt(row_map.get(t), 2) for t in tariffs])

    # ── Traceability ──────────────────────────────────────────────────────
    section("TRACEABILITY AND GOVERNANCE")
    kv("Report ID", ctx.report_id)
    kv("Input Snapshot Hash (SHA-256 prefix)", ctx.input_hash)
    kv("Calculation Model", "MASTER-ENERGY-OPTIMIZATION-01 / P1+P2-D")
    kv("Application Version", ctx.app_version)
    kv("Digital Weld Passport Reference", ctx.passport_id or "Not linked")
    kv("Disclaimer", _DISCLAIMER_SHORT)

    # ── Disclaimer ────────────────────────────────────────────────────────
    section("ENGINEERING DISCLAIMER")
    w.writerow([_DASHBOARD_DISCLAIMER])

    return ("﻿" + buf.getvalue()).encode("utf-8")


# ── XLSX generator ────────────────────────────────────────────────────────────

_HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
_SECTION_FILL = PatternFill("solid", fgColor="2D4A6E")
_WARN_FILL = PatternFill("solid", fgColor="7A3500")
_ROW_ALT_FILL = PatternFill("solid", fgColor="1A2942")


def _xl_header(ws, row: int, cols: list[str]) -> None:
    for ci, h in enumerate(cols, 1):
        c = ws.cell(row=row, column=ci, value=h)
        c.font = Font(bold=True, color="FFFFFF", size=9)
        c.fill = _HEADER_FILL
        c.alignment = Alignment(wrap_text=True)


def _xl_row(ws, row: int, vals: list, alt: bool = False) -> None:
    for ci, v in enumerate(vals, 1):
        sv = "" if v is None else v
        if isinstance(sv, str):
            sv = _safe_cell(sv)
        ws.cell(row=row, column=ci, value=sv)
    if alt:
        for ci in range(1, len(vals) + 1):
            ws.cell(row=row, column=ci).fill = _ROW_ALT_FILL


def _xl_kv(ws, row: int, key: str, val: str) -> None:
    ws.cell(row=row, column=1, value=key).font = Font(bold=True, color="9FB4CC", size=9)
    ws.cell(row=row, column=2, value=_safe_cell(val)).font = Font(color="FFFFFF", size=9)


def _xl_section_title(ws, row: int, title: str, n_cols: int) -> None:
    ws.cell(row=row, column=1, value=title).font = Font(bold=True, color="58A6FF", size=10)
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=max(n_cols, 2))


def generate_xlsx_report(ctx: ReportContext) -> bytes:
    """Return XLSX bytes with multiple sheets."""
    wb = openpyxl.Workbook()

    # ── Sheet 1: Summary ──────────────────────────────────────────────────
    ws = wb.active
    ws.title = "Summary"
    ws.sheet_view.showGridLines = False

    r = 1
    _xl_section_title(ws, r, ctx.report_title or "Energy Analysis Report", 4)
    r += 1

    meta = [
        ("Report ID", ctx.report_id),
        ("Generated At (UTC)", ctx.generated_at),
        ("Application Version", ctx.app_version),
        ("Input Hash", ctx.input_hash),
        ("Project ID", ctx.project_id or "—"),
        ("Project Name", ctx.project_name or "—"),
        ("Part ID", ctx.part_id or "—"),
        ("Digital Weld Passport", ctx.passport_id or "Not linked"),
        ("Analyst", ctx.analyst_name or "—"),
    ]
    for k, v in meta:
        _xl_kv(ws, r, k, v)
        r += 1
    r += 1

    _xl_section_title(ws, r, "Part KPI Summary", 4)
    r += 1
    a = ctx.aggr
    kpis = [
        ("Total Points", str(a.part_point_count)),
        ("In-Window", str(a.part_points_in_window)),
        ("Below Min", str(a.part_points_below_min)),
        ("Above Max", str(a.part_points_above_max)),
        ("Not Established", str(a.part_points_not_established)),
        ("Quality Risk", str(a.part_points_quality_risk)),
        ("Part E_current (kJ)", _fmt(a.part_e_current_total_kj)),
        ("Part E_ideal (kJ)", _fmt(a.part_e_ideal_total_kj)),
        ("Part E_excess (kJ) [THEORETICAL]", _fmt(a.part_e_excess_total_kj)),
    ]
    if a.annual_cost_eur is not None:
        kpis.append(("Annual Cost EUR [THEORETICAL]", _fmt(a.annual_cost_eur, 2)))
    if a.annual_cost_usd is not None:
        kpis.append(("Annual Cost USD [THEORETICAL]", _fmt(a.annual_cost_usd, 2)))
    for k, v in kpis:
        _xl_kv(ws, r, k, v)
        r += 1
    r += 1

    _xl_section_title(ws, r, "⚠ Engineering Disclaimer", 4)
    r += 1
    ws.cell(row=r, column=1, value=_DISCLAIMER_SHORT).font = Font(color="F0B429", size=8)
