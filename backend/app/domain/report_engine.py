"""
report_engine.py — P2-F Professional Engineering Report Generator.

Generates CSV, XLSX and PDF energy analysis reports from multi-spot
weld energy data. All financial values are labeled THEORETICAL.

CONTRACT:
  - No database access, no I/O beyond what the caller requests.
  - NOT_ESTABLISHED energy bounds are never fabricated.
  - Formula injection is prevented in CSV and XLSX outputs.
  - PDF uses Latin-1 core fonts; non-ASCII values in metadata fields are
    transliterated. Numeric values, status codes and English labels are
    unaffected. (Known limitation: full Unicode PDF requires bundled fonts.)
  - All generated bytes are valid and openable in their respective applications.
"""

